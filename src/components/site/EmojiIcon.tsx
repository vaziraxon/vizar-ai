/** Brand violet by default; pass a className to override (e.g. white on a violet tile). */
export function EmojiIcon({ emoji, className = "text-violet-700 dark:text-violet-200", strokeWidth = 1.7 }: { emoji: string; className?: string; strokeWidth?: number }) {
  // Variation selectors (U+FE0F) don't change which picture is meant
  const Icon = ICONS[emoji.replace(/️/g, "")] ?? Sparkles;
  return <Icon aria-hidden="true" size="1em" strokeWidth={strokeWidth} className={className} />;
}
